import {test} from 'node:test';
import assert from 'node:assert/strict';

test('dedicated product pages preserve permissions, variant navigation and return context',{skip:!process.env.VITA_TEST_URL},async()=>{
  const base=new URL(process.env.VITA_TEST_URL);
  assert.ok(['localhost','127.0.0.1'].includes(base.hostname));
  const login=await fetch(new URL('/api/auth/login',base),{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:process.env.ADMIN_USERNAME,password:process.env.ADMIN_PASSWORD})});
  const headers={cookie:login.headers.get('set-cookie').split(';')[0],'content-type':'application/json'};
  const detail='/admin/biblioteca/productos/active-pro-fresa?q=fresa&pagina=2';
  assert.equal((await fetch(new URL(detail,base),{redirect:'manual'})).status,307);
  const page=await fetch(new URL(detail,base),{headers});
  assert.equal(page.status,200);
  const html=await page.text();
  assert.match(html,/product-detail/);
  assert.match(html,/Active Pro/);
  assert.match(html,/<h1[^>]*id="product-title"[^>]*>Active Pro<\/h1><p class="product-presentation product-net-content">770 g · 14 porciones<\/p>/);
  assert.ok(html.indexOf('product-net-content')<html.indexOf('product-description'));
  assert.match(html,/Indicaciones por confirmar/);
  assert.ok(html.includes('href="/admin/biblioteca/productos?q=fresa&amp;pagina=2"'));
  assert.ok(html.includes('href="/admin/biblioteca/productos/active-pro-chocolate?q=fresa&amp;pagina=2"'));
  assert.ok(!html.includes('product-grid'));
  const listing=await(await fetch(new URL('/admin/biblioteca/productos',base),{headers})).text();
  assert.ok(!listing.includes('product-instructions'));
  assert.ok(!listing.includes('Ingredientes mencionados'));
  assert.ok(!listing.includes('Por confirmar'));
  assert.equal((await fetch(new URL('/admin/biblioteca/productos/missing',base),{headers})).status,404);
  const second=await(await fetch(new URL('/admin/biblioteca/productos?pagina=2',base),{headers})).text();
  assert.match(second,/Macchiato/);
  const created=await(await fetch(new URL('/api/links',base),{method:'POST',headers,body:JSON.stringify({recipientName:'Prueba fichas',validDays:7,maxOpens:1})})).json();
  const {link}=created;
  const url='/guia/'+link.token+'/productos/hc-fit?q=capsulas&pagina=2';
  const pending=await fetch(new URL(url,base),{redirect:'manual'});
  assert.equal(pending.status,307);
  assert.equal(new URL(pending.headers.get('location'),base).searchParams.get('producto'),'hc-fit');
  const entry=await fetch(new URL(pending.headers.get('location'),base),{redirect:'manual'});
  assert.equal(entry.status,303);
  const destination=new URL(entry.headers.get('location'),base);
  assert.equal(destination.pathname,'/guia/'+link.token+'/productos/hc-fit');
  assert.equal(destination.searchParams.get('q'),'capsulas');
  const guideHeaders={cookie:entry.headers.get('set-cookie').split(';')[0]};
  const customer=await(await fetch(destination,{headers:guideHeaders})).text();
  assert.ok(customer.includes('product-detail'));
  assert.ok(!customer.includes('Panel administrativo'));
  assert.ok(!customer.includes('Cerrar sesión'));
  assert.equal((await fetch(new URL('/guia/'+link.token+'/productos/ahcc-plus',base),{headers:guideHeaders})).status,200);
  const links=await(await fetch(new URL('/api/links',base),{headers})).json();
  assert.equal(links.links.find(p=>p.id===link.id).openCount,1);
  await fetch(new URL('/api/links/'+link.id,base),{method:'PATCH',headers});
  const revoked=await(await fetch(new URL(url,base),{headers:guideHeaders})).text();
  assert.ok(!revoked.includes('product-detail'));
  assert.match(revoked,/desactivado/);
  const {advisor}=await(await fetch(new URL('/api/advisors',base),{method:'POST',headers,body:JSON.stringify({name:'Prueba fichas asesor',contact:'fichas@example.test'})})).json();
  const advisorUrl='/asesor/'+advisor.token+'/biblioteca/productos/support-plus';
  const advisorHtml=await(await fetch(new URL(advisorUrl,base))).text();
  assert.ok(advisorHtml.includes('product-detail'));
  assert.ok(advisorHtml.includes('Mi panel'));
  assert.ok(!advisorHtml.includes('Panel administrativo'));
  await fetch(new URL('/api/advisors/'+advisor.id,base),{method:'PATCH',headers});
  assert.ok(!(await(await fetch(new URL(advisorUrl,base))).text()).includes('product-detail'));
});
